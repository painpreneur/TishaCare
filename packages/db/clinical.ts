export function interpretBeck(score: number): { diagnosis: string; recommendation: string } {
  if (score <= 9) {
    return {
      diagnosis: "отсутствие депрессивных симптомов",
      recommendation:
        "Признаков депрессии не выявлено. Продолжайте заботиться о своем психическом здоровье.",
    };
  }
  if (score <= 15) {
    return {
      diagnosis: "лёгкая депрессия (субдепрессия)",
      recommendation:
        "Рекомендуется обратить внимание на режим сна, активность и обсудить состояние с врачом при следующем визите.",
    };
  }
  if (score <= 19) {
    return {
      diagnosis: "умеренная депрессия",
      recommendation: "Рекомендуется в ближайшее время обсудить симптомы с лечащим врачом.",
    };
  }
  if (score <= 29) {
    return {
      diagnosis: "выраженная депрессия (средней тяжести)",
      recommendation: "Рекомендуется срочно связаться с лечащим врачом для коррекции терапии.",
    };
  }
  return {
    diagnosis: "тяжёлая депрессия",
    recommendation:
      "Результат указывает на тяжёлое состояние. Пожалуйста, свяжитесь с врачом как можно скорее.",
  };
}

