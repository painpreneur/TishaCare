export interface MdqResult {
  yesCount: number;
  coOccurrence: boolean;
  impact: number;
  positive: boolean;
  diagnosis: string;
  recommendation: string;
}

export function interpretMdq(symptomAnswers: boolean[], coOccurrence: boolean, impact: number): MdqResult {
  const yesCount = symptomAnswers.filter(Boolean).length;
  const positive = yesCount >= 7 && coOccurrence && impact >= 2;

  return {
    yesCount,
    coOccurrence,
    impact,
    positive,
    diagnosis: positive
      ? "положительный скрининг на расстройство биполярного спектра"
      : "отрицательный скрининг",
    recommendation: positive
      ? "Результат указывает на возможное расстройство биполярного спектра. Рекомендуется очная консультация психиатра для уточнения диагноза — MDQ является скрининговым, а не диагностическим инструментом."
      : "Значимых признаков расстройства биполярного спектра не выявлено по результатам скрининга.",
  };
}

/** Score persisted for MDQ combines symptom count (0-13) with impact (0-3) for a single sortable number, e.g. дашборд. */
export function mdqScore(result: MdqResult): number {
  return result.yesCount;
}
